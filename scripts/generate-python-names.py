"""Generate Python named-character lookup from pinned Unicode 17 text data.

No downloaded cache is retained. The existing Unicode license applies to the
source facts; this generator and the lookup implementation are first-party.
"""
import hashlib
import json
from pathlib import Path
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
SOURCES = {
    'UnicodeData.txt': '2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c',
    'NameAliases.txt': '793f6f1e4d15fd90f05ae66460191dc4d75d1fea90136a25f30dd6a4cb950eac',
}
PREFIX = 'https://www.unicode.org/Public/17.0.0/ucd/'


def read_source(name, digest):
    data = urllib.request.urlopen(PREFIX + name, timeout=30).read()
    if hashlib.sha256(data).hexdigest() != digest:
        raise SystemExit('Unicode source digest mismatch: ' + name)
    return data.decode('utf-8').splitlines()


def generate():
    names = {}
    ranges = []
    pending = None
    for line in read_source('UnicodeData.txt', SOURCES['UnicodeData.txt']):
        fields = line.split(';')
        code, name = int(fields[0], 16), fields[1]
        if name.endswith(', First>'):
            pending = (code, name)
        elif name.endswith(', Last>'):
            first, label = pending
            if label.startswith('<CJK Ideograph'):
                ranges.append((first, code, 'CJK UNIFIED IDEOGRAPH-'))
            elif label.startswith('<Tangut Ideograph'):
                ranges.append((first, code, 'TANGUT IDEOGRAPH-'))
            pending = None
        elif not name.startswith('<'):
            names[name] = code
    # Unicode Standard section 3.12: algorithmic Hangul syllable names.
    leading = 'G GG N D DD R M B BB S SS NG J JJ C K T P H'.split()
    leading[11] = ''
    vowel = 'A AE YA YAE EO E YEO YE O WA WAE OE YO U WEO WE WI YU EU YI I'.split()
    trailing = [''] + 'G GG GS N NJ NH D L LG LM LB LS LT LP LH M B BS S SS NG J C K T P H'.split()
    for l_index, left in enumerate(leading):
        for v_index, middle in enumerate(vowel):
            for t_index, right in enumerate(trailing):
                names['HANGUL SYLLABLE ' + left + middle + right] = 0xAC00 + (l_index * 21 + v_index) * 28 + t_index
    for line in read_source('NameAliases.txt', SOURCES['NameAliases.txt']):
        line = line.split('#', 1)[0].strip()
        if line:
            code, name, _ = line.split(';')
            names[name] = int(code, 16)
    output = '// SPDX-FileCopyrightText: 2025 Unicode, Inc.\n'
    output += '// SPDX-License-Identifier: Unicode-3.0\n'
    output += '// Generated by scripts/generate-python-names.py from Unicode 17.0.0.\n'
    output += '// Source data license: vendor/unicode/LICENSE. Do not edit.\n'
    output += '#![allow(clippy::unreadable_literal)]\n'
    output += 'pub(super) const NAMES: &[(&str, u32)] = &[\n'
    output += ''.join(f'    ({json.dumps(name)}, 0x{code:X}),\n' for name, code in sorted(names.items()))
    output += '];\npub(super) const RANGES: &[(u32, u32, &str)] = &[\n'
    output += ''.join(f'    (0x{start:X}, 0x{end:X}, {json.dumps(prefix)}),\n' for start, end, prefix in ranges)
    output += '];\n'
    target = ROOT / 'crates/core/src/grammar/codec/python_names_data.rs'
    target.write_text(output)
    manifest = {
        'sources': {name: {'url': PREFIX + name, 'sha256': digest} for name, digest in SOURCES.items()},
        'output': str(target.relative_to(ROOT)),
        'sha256': hashlib.sha256(output.encode()).hexdigest(),
        'names': len(names),
        'algorithmic_ranges': len(ranges),
    }
    generated_path = ROOT / 'vendor/unicode/generated.json'
    generated = json.loads(generated_path.read_text())
    generated[str(target.relative_to(ROOT))] = manifest['sha256']
    generated_path.write_text(json.dumps(generated, indent=2) + '\n')
    (ROOT / 'vendor/unicode/python-names.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print(f'Generated {len(names)} names and {len(ranges)} algorithmic ranges.')


if __name__ == '__main__':
    generate()
