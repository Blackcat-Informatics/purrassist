"""Generate the offline entity lookup from hash-pinned WHATWG data."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
manifest = json.loads((ROOT / 'vendor/entities/manifest.json').read_text())
for name, entry in manifest['files'].items():
    if hashlib.sha256((ROOT / name).read_bytes()).hexdigest() != entry['sha256']:
        raise SystemExit(f'{name}: source digest mismatch')
data = json.loads((ROOT / 'crates/core/tests/data/entities/entities.json').read_text())
lines = [
    '// SPDX-FileCopyrightText: WHATWG (Apple, Google, Mozilla, Microsoft).',
    '// SPDX-License-Identifier: BSD-3-Clause',
    '// Generated by scripts/generate-entities.py; do not edit.',
    '// Source: https://html.spec.whatwg.org/entities.json; see LICENSE-WHATWG.',
    '#[rustfmt::skip]',
    'pub(super) static NAMED: &[(&str, &str)] = &[',
]
for name, entry in sorted(data.items()):
    if not name.endswith(';'):
        continue
    assert entry['characters'] == ''.join(map(chr, entry['codepoints']))
    value = ''.join('\\u{' + format(code, 'x') + '}' for code in entry['codepoints'])
    lines.append(f'    ("{name}", "{value}"),')
lines.append('];')
target = ROOT / 'crates/core/src/markdown/inline/entity_data.rs'
target.write_text('\n'.join(lines) + '\n')
(ROOT / 'vendor/entities/generated.json').write_text(json.dumps({
    str(target.relative_to(ROOT)): hashlib.sha256(target.read_bytes()).hexdigest()
}, indent=2) + '\n')
